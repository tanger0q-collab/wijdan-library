import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID,createHash} from 'node:crypto';

const origin=process.env.WIJDAN_TEST_ORIGIN || 'http://localhost:8788';
const key=process.env.WIJDAN_TEST_KEY || 'a'.repeat(43);
const request=(url,init={})=>fetch(origin+'/api/'+url,{...init,headers:{Origin:origin,...init.headers}});
const hash=buffer=>createHash('sha256').update(buffer).digest('hex');

test('private storage supports range reads and revision conflicts', {timeout:60_000}, async()=>{
  assert.equal((await request('changes')).status,401);
  const logged=await request('login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({key,role:'student'})});
  assert.equal(logged.status,200);
  const Cookie=logged.headers.get('set-cookie').split(';')[0];
  const headers={Cookie,'Content-Type':'application/json'};
  const id=randomUUID(), recordId='test:'+randomUUID();
  const version=rev=>({method:'PUT',headers,body:JSON.stringify({kind:'index',rev,data:{version:rev}})});
  const first=await request('records/'+recordId,version(0));
  assert.equal(first.status,200);
  const stale=await request('records/'+recordId,version(0));
  assert.equal(stale.status,409);
  assert.equal((await stale.json()).current.rev,1);
  const current=await request('records/'+recordId,version(1));
  assert.equal((await current.json()).rev,2);
  const body=Buffer.from(Array.from({length:840000},(_,index)=>index%251));
  const uploaded=await request('blob/'+id,{method:'PUT',headers:{Cookie,'Content-Type':'application/pdf'},body});
  assert.equal(uploaded.status,200);
  assert.equal((await request('blob/'+id)).status,401);
  const start=786400,end=786499;
  const range=await request('blob/'+id,{headers:{Cookie,Range:'bytes='+start+'-'+end}});
  assert.equal(range.status,206);
  assert.equal(range.headers.get('content-range'),'bytes '+start+'-'+end+'/'+body.length);
  assert.equal(hash(Buffer.from(await range.arrayBuffer())),hash(body.subarray(start,end+1)));
  const duplicate=await request('blob/'+id,{method:'PUT',headers:{Cookie,'Content-Type':'application/pdf'},body:Buffer.from('overwrite')});
  assert.equal(duplicate.status,409);
  const full=await request('blob/'+id,{headers:{Cookie}});
  assert.equal(hash(Buffer.from(await full.arrayBuffer())),hash(body));
  const multipart=randomUUID();
  const created=await request('multipart/'+multipart,{method:'POST',headers,body:JSON.stringify({type:'application/pdf'})});
  assert.equal(created.status,200);
  const job=encodeURIComponent((await created.json()).uploadId);
  const partData=Buffer.alloc(2*1024*1024+17,92);
  const part=await request('multipart/'+multipart+'/'+job+'/1',{method:'PUT',headers:{Cookie},body:partData});
  assert.equal(part.status,200);
  const completed=await request('multipart/'+multipart+'/'+job,{method:'POST',headers,body:JSON.stringify({parts:[await part.json()]})});
  assert.equal(completed.status,200);
  const data=await request('blob/'+multipart,{headers:{Cookie,Range:'bytes=524280-524320'}});
  assert.equal(data.status,206);
  assert.equal(hash(Buffer.from(await data.arrayBuffer())),hash(partData.subarray(524280,524321)));
  assert.equal((await request('owner/status',{headers:{Cookie}})).status,403);
  assert.equal((await request('logout',{method:'POST',headers})).status,200);
  assert.equal((await request('changes',{headers:{Cookie}})).status,401);
});
